export const LANGUAGE_STORAGE_KEY = 'bhunetra_selected_language';

export const getStoredLanguage = (): LanguageCode => {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY) as LanguageCode;
    if (saved && TRANSLATIONS[saved]) {
      return saved;
    }
  } catch {
    // Local storage unavailable or restricted in sandbox
  }
  return 'en';
};

export const setStoredLanguage = (lang: LanguageCode): void => {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch {
    // Local storage unavailable or restricted in sandbox
  }
};

export const getTranslation = (lang?: LanguageCode | string): TranslationDictionary => {
  const code = (lang as LanguageCode) || 'en';
  const selected = TRANSLATIONS[code] || TRANSLATIONS.en;
  // Fallback guarantee: merge with English so no missing keys
  return {
    ...TRANSLATIONS.en,
    ...selected
  };
};
